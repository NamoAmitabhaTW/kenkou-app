/// パタカラ 的四個音節。
///
/// 這是**語音辨識的輸出詞彙**,不是健口操專屬的東西:健口操拿它當「要說哪個音」
/// 的目標,吃金幣拿同樣四個音當方向鍵。兩邊共用同一顆模型、同一套對照表,
/// 判定行為才會完全一致 —— 所以它放在 shared 而不是任何一個 feature 裡。
///
/// 標示一律用國字。送氣不送氣都算(辨識端 ㄅ/ㄉ/ㄍ 開頭的字也收),練的是嘴唇
/// 和舌頭的動作,不是聲母。哪些字算哪個音節見 `syllable_map.dart`。
enum Syllable {
  pa(label: '怕'),
  ta(label: '踏'),
  ka(label: '卡'),
  // 國語沒有 r + a 的音節,ㄌㄚ 最貼近日文ラ行的 [ɾa],所以寫成「啦」。
  ra(label: '啦');

  const Syllable({required this.label});

  /// 畫面上顯示的字。
  final String label;
}
